import { fs, path } from '../../config.root/external.packages.js';
import { buildOutputFolderName } from '../../config.root/root.js';
//-

const renameRootTypeFileInBuildOutputFolder = () => {
  const _defaultDtsFileName = 'index.d.ts';
  //-
  const buildFolderRoot = path.resolve(process.cwd(), buildOutputFolderName);
  const expectedDtsTypeFile = path.join(buildFolderRoot, _defaultDtsFileName);
  //----------------------------------------------------------------
  // Find the current root type file and rename index.d.ts (i.e. if
  // there's no index.d.ts detected in build folder root).
  //----------------------------------------------------------------
  if (!fs.existsSync(expectedDtsTypeFile)) {
    const generatedFiles = fs.readdirSync(buildFolderRoot);
    const dtsTypeFile = generatedFiles.find((dtsFile) =>
      dtsFile.endsWith('.d.ts'),
    );
    //-
    if (dtsTypeFile) {
      fs.renameSync(
        path.join(buildFolderRoot, dtsTypeFile),
        expectedDtsTypeFile,
      );
      console.log(
        `[PROD] Root type file ${dtsTypeFile} renamed to ${_defaultDtsFileName}`,
      );
    }
  } else {
    console.log(
      `[PROD] Root ${_defaultDtsFileName} Generated by default: omitting rename operation.`,
    );
  }
};

export { renameRootTypeFileInBuildOutputFolder };
